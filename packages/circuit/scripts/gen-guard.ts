// Writes artifacts/guard.json and docs/guard-truth-table.md. Run: pnpm --filter @signet/circuit gen
import { writeFileSync, readFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { guardArtifact } from './artifact.ts';
import { guard, guardInputsOf, GUARD_COMBINATIONS, GUARD_INPUTS, GUARD_MEANING } from '../src/guard-reference.ts';

const here = fileURLToPath(new URL('.', import.meta.url));
const a = guardArtifact();
const depPath = `${here}../artifacts/guard-deployment.json`;
const dep = existsSync(depPath) ? JSON.parse(readFileSync(depPath, 'utf8')) : null;
if (dep && dep.netlistSha256 !== a.netlistSha256) throw new Error('guard-deployment.json is for a different netlist');
writeFileSync(`${here}../artifacts/guard.json`, JSON.stringify(a, null, 2) + '\n');
const okl = (h: string) => `[\`${h.slice(0, 10)}…${h.slice(-4)}\`](https://web3.okx.com/explorer/x-layer/evm/tx/${h})`;
const onChain = dep
  ? `**Processor #${dep.processorIndex} \`${dep.processor}\`, circuit ID ${dep.circuitId}**. Mint ${okl(dep.mintTx)}, tape-out ${okl(dep.tapeoutTx)}. All 512 rows checked with \`eval\` on mainnet at block ${dep.verifiedAtBlock} on two RPC operators`
  : '_not taped out on mainnet yet_ (taped out on the staging fork by `pnpm staging:up`; the mainnet plan is in `docs/mainnet-plan.md`)';
const b = (v: boolean) => (v ? '1' : '0');
const rows = Array.from({ length: GUARD_COMBINATIONS }, (_, n) => ({ n, x: guardInputsOf(n), o: guard(guardInputsOf(n)) }));
const out = (o: ReturnType<typeof guard>) => (o.BLOCK ? 'BLOCK' : o.WARN ? 'WARN' : 'ALLOW');
const count = (k: string) => rows.filter((r) => out(r.o) === k).length;

let md = `# Signet Guard decision circuit: full truth table

Generated by \`packages/circuit/scripts/gen-guard.ts\` from the reference function \`packages/circuit/src/guard-reference.ts\`. Do not edit by hand.
CI recomputes it and fails if the netlist and the reference disagree on any row.

## What it decides

Before every signing request on a sealed site, Guard works out nine facts and asks this circuit (a \`view\` call to
\`eval\`, cached per input) whether to **ALLOW**, **WARN** (let it through and record it) or **BLOCK** it.

| Input | Meaning |
|---|---|
${GUARD_INPUTS.map((k, i) => `| ${i}. ${k} | ${GUARD_MEANING[k]} |`).join('\n')}

| Rule | Output |
|---|---|
| checked = 0 | WARN (fail-open) |
| a violation (pageMatches, targetSealed, spenderSealed or recipientOk = 0, or revoked = 1), enforce mode | BLOCK |
| a violation, observe mode | WARN |
| no violation, but decoded = 0 or frozen = 1 | WARN |
| otherwise | ALLOW |

Exactly one output is 1 on every row.

## The circuit

| | |
|---|---|
| Inputs | ${a.nIn} (${a.inputs.join(', ')}), so **${GUARD_COMBINATIONS} combinations**, all listed below |
| Outputs | ${a.nOut} (${a.outputs.join(', ')}); packed byte bit 0 = ALLOW, bit 1 = WARN, bit 2 = BLOCK |
| Gates | **${a.gates} NAND**, no LATCH (combinational: read with \`eval\`) |
| Netlist (TAP-02 format, ${a.netlist.length / 2 - 1} bytes) | \`${a.netlist}\` |
| Netlist SHA-256 | \`${a.netlistSha256}\` |
| On X Layer mainnet | ${onChain} |

**Check a row yourself** (after the mainnet tape-out): row \`n\` is packed little-endian into 2 bytes, e.g. row 0x13f → \`0x3f01\`:

\`\`\`
cast call 0x73153e5fd2Acac604D49d6ca9fea27b750718F22 "eval(uint256,bytes)(bytes)" <circuitId> 0x3f01 --rpc-url https://xlayerrpc.okx.com
\`\`\`

## Summary

| Output | Rows |
|---|---|
| ALLOW | ${count('ALLOW')} |
| WARN | ${count('WARN')} |
| BLOCK | ${count('BLOCK')} |
| **All** | ${GUARD_COMBINATIONS} |

Rows with enforceMode = 0 and BLOCK = 1: **${rows.filter((r) => !r.x.enforceMode && r.o.BLOCK).length}** (observe mode never blocks). Rows with checked = 0 and BLOCK = 1: **${rows.filter((r) => !r.x.checked && r.o.BLOCK).length}** (fail-open).

## All rows

| row | eval input | ${GUARD_INPUTS.join(' | ')} | **decision** |
|---|---|${GUARD_INPUTS.map(() => '---').join('|')}|---|
`;
for (const r of rows) {
  const packed = `0x${(r.n & 0xff).toString(16).padStart(2, '0')}${(r.n >> 8).toString(16).padStart(2, '0')}`;
  md += `| 0x${r.n.toString(16).padStart(3, '0')} | \`${packed}\` | ${GUARD_INPUTS.map((k) => b(r.x[k])).join(' | ')} | **${out(r.o)}** |\n`;
}
writeFileSync(`${here}../../../docs/guard-truth-table.md`, md);
console.log(`guard circuit: ${a.gates} gates, sha256 ${a.netlistSha256}; ALLOW ${count('ALLOW')}, WARN ${count('WARN')}, BLOCK ${count('BLOCK')}`);
