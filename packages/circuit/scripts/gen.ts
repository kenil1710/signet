// Writes artifacts/policy.json and docs/policy-truth-table.md. Run: pnpm --filter @signet/circuit gen
import { writeFileSync, readFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { artifact } from './artifact.ts';
import { policy, inputsOf, N_COMBINATIONS, INPUTS } from '../src/reference.ts';

const here = fileURLToPath(new URL('.', import.meta.url));
const a = artifact();
const depPath = `${here}../artifacts/deployment.json`;
const dep = existsSync(depPath) ? JSON.parse(readFileSync(depPath, 'utf8')) : null;
if (dep && dep.netlistSha256 !== a.netlistSha256) throw new Error('deployment.json is for a different netlist');
const okl = (h: string) => `[\`${h.slice(0, 10)}…${h.slice(-4)}\`](https://web3.okx.com/explorer/x-layer/evm/tx/${h})`;
const onChain = dep
  ? `**Processor #${dep.processorIndex} \`${dep.processor}\`, circuit ID ${dep.circuitId}** (chain ${dep.chainId}). Mint ${okl(dep.mintTx)}, tape-out ${okl(dep.tapeoutTx)} (block ${dep.tapeoutBlock}). All 512 rows checked with \`eval\` on mainnet at block ${dep.verifiedAtBlock} on two RPC operators: 512/512 match`
  : '_not taped out yet_';
const cpuArg = dep ? dep.processor : '<processor>';
const idArg = dep ? String(dep.circuitId) : '<circuitId>';
writeFileSync(`${here}../artifacts/policy.json`, JSON.stringify(a, null, 2) + '\n');

const b = (v: boolean) => (v ? '1' : '0');
const TIERS: Record<string, string> = { '00': 'Code only', '01': 'New external origin', '10': 'New contract / spender', '11': 'Admin change' };
const RULES: Record<string, string> = {
  '00': '≥1 approval and tS, or 3 of 3 with e',
  '01': '≥2 approvals and tS',
  '10': '≥2 approvals and tL, or 3 of 3 with e',
  '11': '3 of 3 and tL, no fast lane',
};
const rows = Array.from({ length: N_COMBINATIONS }, (_, n) => ({ n, x: inputsOf(n), o: policy(inputsOf(n)) }));
const count = (pred: (r: (typeof rows)[number]) => boolean) => rows.filter(pred).length;

let md = `# Signet release-policy circuit: full truth table

Generated by \`packages/circuit/scripts/gen.ts\` from the reference function \`packages/circuit/src/reference.ts\`. Do not edit by hand.
CI recomputes it and fails if the netlist and the reference ever disagree on any row.

## What the circuit decides

ReleaseGate supplies the facts as input bits (never CI). The circuit answers two questions: may this release be published (**PUBLISH**), and may the project be unfrozen (**UNFREEZE**).

| Input | Meaning | Set by |
|---|---|---|
| a0, a1, a2 | Approver 1/2/3 signed | ReleaseGate, from on-chain approvals |
| tS | Short timelock passed (default 1 h) | ReleaseGate, block.timestamp |
| tL | Long timelock passed (default 24 h) | ReleaseGate, block.timestamp |
| r1 r0 | Risk tier, computed on-chain by comparing hashes | ReleaseGate |
| f | Project is frozen | ReleaseGate state |
| e | Emergency fast lane requested | Proposer |

| Tier r1 r0 | When | PUBLISH rule |
|---|---|---|
${Object.keys(TIERS).map((t) => `| ${t} | ${TIERS[t]} | ${RULES[t]} |`).join('\n')}

If **f** = 1, PUBLISH = 0. **UNFREEZE** = at least 2 approvals.

## The circuit

| | |
|---|---|
| Inputs | ${a.nIn} (${a.inputs.join(', ')}), so **${N_COMBINATIONS} combinations**, all listed below |
| Outputs | ${a.nOut} (${a.outputs.join(', ')}) |
| Gates | **${a.gates} NAND**, no LATCH (combinational: read with \`eval\`) |
| Netlist (TAP-02 format, ${a.netlist.length / 2 - 1} bytes) | \`${a.netlist}\` |
| Netlist SHA-256 | \`${a.netlistSha256}\` |
| On X Layer mainnet | ${onChain} |

**Check any row yourself**: input number \`n\` from the table is packed little-endian into 2 bytes (input i = bit i), for example row 0x1a9 → \`0xa901\`:

\`\`\`
cast call ${cpuArg} "eval(uint256,bytes)(bytes)" ${idArg} 0xa901 --rpc-url https://xlayerrpc.okx.com
\`\`\`

The answer byte is bit 0 = PUBLISH, bit 1 = UNFREEZE (\`0x00\`, \`0x01\`, \`0x02\` or \`0x03\`). To check all 512 rows at once: \`node packages/circuit/scripts/verify-mainnet.ts ${cpuArg} ${idArg}\`.

## Summary

| Tier | Rows | PUBLISH = 1 | of which via fast lane only |
|---|---|---|---|
${Object.keys(TIERS)
  .map((t) => {
    const inTier = (r: (typeof rows)[number]) => `${b(r.x.r1)}${b(r.x.r0)}` === t;
    const pub = count((r) => inTier(r) && r.o.PUBLISH);
    const fastOnly = count((r) => inTier(r) && r.o.PUBLISH && !(t[0] === '0' ? r.x.tS : r.x.tL));
    return `| ${t} ${TIERS[t]} | ${count(inTier)} | ${pub} | ${fastOnly} |`;
  })
  .join('\n')}
| **All** | ${N_COMBINATIONS} | ${count((r) => r.o.PUBLISH)} | |

Rows with f = 1 and PUBLISH = 1: **${count((r) => r.x.f && r.o.PUBLISH)}**. Rows with UNFREEZE = 1: ${count((r) => r.o.UNFREEZE)}.

`;
for (const t of Object.keys(TIERS)) {
  md += `## Tier ${t}: ${TIERS[t]} (${RULES[t]})\n\n| row | eval input | a0 | a1 | a2 | tS | tL | r1 | r0 | f | e | **PUBLISH** | **UNFREEZE** |\n|---|---|---|---|---|---|---|---|---|---|---|---|---|\n`;
  for (const r of rows.filter((r) => `${b(r.x.r1)}${b(r.x.r0)}` === t)) {
    const packed = `0x${(r.n & 0xff).toString(16).padStart(2, '0')}${(r.n >> 8).toString(16).padStart(2, '0')}`;
    md += `| 0x${r.n.toString(16).padStart(3, '0')} | \`${packed}\` | ${INPUTS.map((k) => b(r.x[k])).join(' | ')} | **${b(r.o.PUBLISH)}** | ${b(r.o.UNFREEZE)} |\n`;
  }
  md += '\n';
}
writeFileSync(`${here}../../../docs/policy-truth-table.md`, md);
console.log(`gates ${a.gates}, netlist ${a.netlist.length / 2 - 1} bytes, sha256 ${a.netlistSha256}`);
console.log(`PUBLISH=1 rows: ${count((r) => r.o.PUBLISH)}/${N_COMBINATIONS}`);
