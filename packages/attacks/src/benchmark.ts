// The comparison benchmark (docs/benchmark.md): the same attack suite against three defenders, each in its own run
// with fresh projects on the staging chain. pnpm benchmark (needs pnpm staging:up; about 25 minutes).
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../../..', import.meta.url));
const SUITE = fileURLToPath(new URL('./suite.ts', import.meta.url));
const DEFENDERS = [
  { id: 'sri-only', name: '(a) SRI only', what: 'No extension. The site puts an `integrity` (SRI) attribute on every `<script>` and stylesheet in its HTML, the best a careful team can do with the browser alone.' },
  { id: 'hash-only', name: '(b) Hash-only checker', what: 'An extension that compares the bytes the page loaded with hashes published on-chain and blocks the page on a mismatch, with **no signing-time check**. This is the approach of TEE Shield and Meta Code Verify. It is modelled here as Signet Guard with its sealed allowlist switched off (`GUARD_MODE=hash-only`), not as those products themselves.' },
  { id: 'signet', name: '(c) Signet', what: 'Guard: the page check plus the signing-time allowlist decided by the Guard circuit, enforce mode.' },
] as const;

interface Run { defender: string; blocked: number; total: number; falseBlocks: number; clean: number; attacks: { id: string; vector: string; blocked: boolean; how: string }[] }
const only = process.argv.slice(2);
for (const d of DEFENDERS) {
  if (only.length && !only.includes(d.id)) continue;
  console.log(`\n===== ${d.name} =====`);
  spawnSync('bash', [join(ROOT, 'staging/renew-operator.sh')], { stdio: 'inherit' });
  const r = spawnSync(process.execPath, [SUITE], { stdio: 'inherit', env: { ...process.env, SIGNET_DEFENDER: d.id, GUARD_MODE: d.id === 'hash-only' ? 'hash-only' : '' } });
  if (r.status !== 0) {
    console.error(`the ${d.id} run failed`);
    process.exit(1);
  }
}
const runs = DEFENDERS.map((d) => ({ ...d, r: JSON.parse(readFileSync(join(ROOT, `docs/demo/benchmark-${d.id}.json`), 'utf8')) as Run }));
const [sri, hash, sig] = runs.map((x) => x.r);
const ids = sig!.attacks.map((a) => a.id);
const cell = (r: Run, id: string) => {
  const a = r.attacks.find((x) => x.id === id);
  return !a ? 'n/a' : a.blocked ? '**blocked**' : 'missed';
};
const headline = `Against the same ${sig!.total} attacks on a fork of X Layer, SRI alone blocked ${sri!.blocked}, a hash-only checker blocked ${hash!.blocked}, and Signet blocked ${sig!.blocked}, with ${sig!.falseBlocks} false blocks on ${sig!.clean} clean sessions.`;
const md = `# Benchmark: SRI vs a hash-only checker vs Signet

**${headline}**

Generated by \`pnpm benchmark\` (\`packages/attacks/src/benchmark.ts\`) on ${new Date().toISOString().slice(0, 10)}. Each defender ran the full
attack suite in its own run, with fresh projects sealed through the real CLI on the staging chain (an anvil fork of
X Layer mainnet), real headless Chromium, and a mock wallet that records every request it receives. An attack is
**blocked** only if the attacker's signature request never reached the wallet.

| Defender | What it is |
|---|---|
${runs.map((x) => `| ${x.name} | ${x.what} |`).join('\n')}

## Results

| Attack | ${runs.map((x) => x.name).join(' | ')} |
|---|${runs.map(() => '---').join('|')}|
${ids.map((id) => `| ${sig!.attacks.find((a) => a.id === id)!.vector} | ${runs.map((x) => cell(x.r, id)).join(' | ')} |`).join('\n')}
| **Blocked** | ${runs.map((x) => `**${x.r.blocked}/${x.r.total}**`).join(' | ')} |
| **False blocks on clean sessions** | ${runs.map((x) => `${x.r.falseBlocks}/${x.r.clean}`).join(' | ')} |

## Reading it fairly

- **The hash-only column is an ablation of Signet**, not a test of TEE Shield or Meta Code Verify. It shares Guard's page check (cache reads, service-worker check, two RPCs), which may be stronger or weaker than theirs. What it isolates is the value of checking *signatures* against a sealed allowlist, not just *files* against hashes.
- **SRI is given its best case**: every script and stylesheet in the HTML carries an integrity attribute. SRI can't protect the HTML itself (an attacker who serves the HTML writes new integrity values) and doesn't cover chunks loaded with \`import()\`.
- **Clean sessions**: SRI has no verified-copy sessions (it has no gateway), so it ran ${sri!.clean} instead of ${sig!.clean}.
- **Not in this table:** a user without any extension is not protected by (b) or (c) either; that case is in \`docs/attack-report.md\` as a stated limit. A compromised extension defeats (b) and (c) (\`THREAT_MODEL.md\`).

## How each attack was stopped

${runs.map((x) => `### ${x.name}\n\n| Attack | Result |\n|---|---|\n${x.r.attacks.map((a) => `| ${a.id} | ${a.blocked ? 'blocked' : 'missed'}: ${a.how.replace(/\|/g, '/')} |`).join('\n')}`).join('\n\n')}
`;
writeFileSync(join(ROOT, 'docs/benchmark.md'), md);
console.log(`\n${headline}`);
